#!/usr/bin/env python
"""Frozen-checkpoint spatial-spectrum covariance probe for field Dual-Wiener.

For each rollout horizon and channel, centered residuals are whitened by their
per-coordinate standard deviation.  The estimator then averages their 2-D
power spectra across balanced physical trajectories.  A noise covector is
generated by filtering real white noise with the square root of that spectrum,
which preserves stationary spatial second-order structure while randomizing
phase and absolute feature location.  Multiplying by the original coordinate
standard deviations restores the diagonal heteroscedasticity exactly in
expectation.

This is a frozen-checkpoint estimator diagnostic.  It compares the existing
diagonal Gaussian with a spatially colored Gaussian on the same fully-open
route graph; it does not equate all residual covariance with irreducible noise.
"""
